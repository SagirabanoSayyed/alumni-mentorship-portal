package com.alumniportal.dto;

public class AdminDashboardDto {

	private long totalUsers;
	private long totalStudents;
	private long totalMentors;
	private long totalAlumni;
	private long totalSessions;
	private long totalFeedback;
	
	
	public long getTotalUsers() {
		return totalUsers;
	}
	public void setTotalUsers(long totalUsers) {
		this.totalUsers = totalUsers;
	}
	public long getTotalStudents() {
		return totalStudents;
	}
	public void setTotalStudents(long totalStudents) {
		this.totalStudents = totalStudents;
	}
	public long getTotalMentors() {
		return totalMentors;
	}
	public void setTotalMentors(long totalMentors) {
		this.totalMentors = totalMentors;
	}
	public long getTotalAlumni() {
		return totalAlumni;
	}
	public void setTotalAlumni(long totalAlumni) {
		this.totalAlumni = totalAlumni;
	}
	public long getTotalSessions() {
		return totalSessions;
	}
	public void setTotalSessions(long totalSessions) {
		this.totalSessions = totalSessions;
	}
	public long getTotalFeedback() {
		return totalFeedback;
	}
	public void setTotalFeedback(long totalFeedback) {
		this.totalFeedback = totalFeedback;
	}
	
	
}
